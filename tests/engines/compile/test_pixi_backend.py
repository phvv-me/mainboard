def test_the_windows_activation_cache_refuses_missing_stale_and_invalid_state(
    pixi: Pixi,
) -> None:
    with pytest.raises(MissionError, match="Windows activation is not cached"):
        pixi._cached_windows_activation()

    pixi.manifest.write_text("[workspace]\n", encoding="utf-8")
    _cache(pixi)
    # Whole seconds apart, since NTFS keeps a modification time only to 100 ns.
    os.utime(pixi.windows_activation_cache, ns=(1_000_000_000, 1_000_000_000))
    os.utime(pixi.manifest, ns=(2_000_000_000, 2_000_000_000))
    with pytest.raises(MissionError, match="Windows activation changed"):
        pixi._cached_windows_activation()

    pixi.windows_activation_cache.write_text(
        json.dumps({"environment_variables": [], "activation_scripts": {}}), encoding="utf-8"
    )
    with pytest.raises(MissionError, match="Windows activation cache is invalid"):
        pixi._cached_windows_activation()


