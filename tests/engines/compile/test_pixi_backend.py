def _cache(pixi: Pixi, *scripts: Path, **variables: str) -> None:
    """Record a Windows activation naming `scripts` and exporting `variables`."""
    pixi.windows_activation_cache.write_text(
        json.dumps(
            {
                "environment_variables": variables,
                "activation_scripts": [str(script) for script in scripts],
            }
        ),
        encoding="utf-8",
    )


