"""Rules over where properties would replace examples (mcmr's PY-TEST property_testing group)."""

from ...catalog import Rule
from .testing_cases import VECTOR_GROUPS


class BroadExamplePropertyCandidateCount(Rule, id="PY-TEST0017"):
    """Groups of many distinct literal cases that a Hypothesis property would cover."""

    minimum_cases: int = 10

    query = f"""
        SELECT f.*, n AS value FROM test_case_group_facts f JOIN (
          SELECT fact_id, count(*) AS n FROM {VECTOR_GROUPS}()
          WHERE vector_count >= $minimum_cases AND vector_count = distinct_vector_count
          GROUP BY fact_id) USING (fact_id)
    """
    message = "broad example property candidate count is {value} for `{fact_id}`"


class ModuleGeneratedParametrizationCount(Rule, id="PY-TEST0018"):
    """Collected tests whose parametrization is generated by module-level code."""

    query = """
        SELECT f.*, n AS value FROM test_function_facts f JOIN (
          SELECT fact_id, sum(generated_parametrization_count) AS n FROM test_function_tests
          WHERE is_collected AND generated_parametrization_count > 0 GROUP BY fact_id)
          USING (fact_id)
    """
    message = "module generated parametrization count is {value} for `{fact_id}`"
