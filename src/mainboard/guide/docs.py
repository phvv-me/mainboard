"""Generate the shell completion scripts and the README's command tree from the declaration.

Build time only: nothing at runtime imports this module, so `mb --help` stays import-free.
`python -m mainboard.guide.docs` rewrites both; the test of the same name fails when the
committed copies differ from a fresh generation.
"""

import os
import subprocess
import sys
from pathlib import Path
from typing import Literal, get_args

from patos import FrozenModel

Shell = Literal["bash", "fish", "zsh"]

# Where each shell's script is committed, beside the module that generates it.
_SCRIPTS: dict[Shell, str] = {"bash": "mb.bash", "fish": "mb.fish", "zsh": "_mb"}
_BEGIN = "<!-- mb-commands:begin (generated by mainboard.guide.docs, do not edit) -->"
_END = "<!-- mb-commands:end -->"
_FENCE = "```"
_TIMEOUT = 120


class CommandDocs(FrozenModel):
    """The files generated from the command declaration.

    readme: the README whose section between the two marker comments holds `MB_AGENT=1 mb --tree`.
    completions: the folder of completion scripts, one per shell.
    """

    readme: Path
    completions: Path

    @classmethod
    def committed(cls) -> CommandDocs:
        """The copies in this checkout: `README.md` at the package root, scripts in `guide/`."""
        here = Path(__file__).resolve().parent
        return cls(readme=here.parents[2] / "README.md", completions=here / "completions")

    @staticmethod
    def _printed(*words: str, env: dict[str, str] | None = None) -> str:
        """What `python -m mainboard WORDS` prints, run as a child with `env` added."""
        return subprocess.run(
            [sys.executable, "-m", "mainboard", *words],
            capture_output=True,
            check=True,
            env={**os.environ, **(env or {})},
            text=True,
            timeout=_TIMEOUT,
        ).stdout

    def _script(self, shell: Shell) -> str:
        """What `mb --completion SHELL` prints, which is cyclopts' `generate_completion`."""
        return self._printed("--completion", shell)

    def _spliced(self) -> str:
        """The README with its marked section replaced by a fenced `MB_AGENT=1 mb --tree`.

        Raises ValueError for a README without the two markers, in order.
        """
        text = self.readme.read_text()
        before, begin, rest = text.partition(_BEGIN)
        _, end, after = rest.partition(_END)
        if not (begin and end):
            raise ValueError(f"{self.readme} lacks the markers {_BEGIN!r} and {_END!r}")
        return f"{before}{begin}\n{_FENCE}text\n{self._tree()}{_FENCE}\n{end}{after}"

    def _tree(self) -> str:
        """What `MB_AGENT=1 mb --tree` prints, so the audience is the agent's."""
        return self._printed("--tree", env={"MB_AGENT": "1"})

    def path(self, shell: Shell) -> Path:
        """Where `shell`'s script is committed."""
        return self.completions / _SCRIPTS[shell]

    def render(self) -> dict[Path, str]:
        """Every generated file as it should read, by path."""
        scripts = {self.path(shell): self._script(shell) for shell in get_args(Shell)}
        return scripts | {self.readme: self._spliced()}

    def stale(self) -> list[Path]:
        """The generated files whose committed text differs from a fresh generation."""
        return [
            path
            for path, text in self.render().items()
            if not path.is_file() or path.read_text() != text
        ]

    def write(self) -> None:
        """Replace every generated file with a fresh generation."""
        self.completions.mkdir(parents=True, exist_ok=True)
        for path, text in self.render().items():
            path.write_text(text)


if __name__ == "__main__":
    CommandDocs.committed().write()
